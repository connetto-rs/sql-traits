//! PostgreSQL 18's `pg_cast` rows.

use alloc::borrow::Cow;

use super::{CastFunction, CastImplementation, PostgresCatalogCast};
use crate::{structs::generic_db::sqlparser::postgres_catalog::CatalogName, traits::CastContext};

/// Builds one row from stored `pg_type` and `pg_proc` names, all in
/// `pg_catalog`.
macro_rules! cast {
    ($source:literal, $target:literal, $context:ident, $method:ident) => {
        PostgresCatalogCast {
            source: CatalogName::in_pg_catalog(Cow::Borrowed($source), false),
            target: CatalogName::in_pg_catalog(Cow::Borrowed($target), false),
            context: CastContext::$context,
            implementation: CastImplementation::$method,
        }
    };
    ($source:literal, $target:literal, $context:ident, $function:literal($($argument:literal),+)) => {
        PostgresCatalogCast {
            source: CatalogName::in_pg_catalog(Cow::Borrowed($source), false),
            target: CatalogName::in_pg_catalog(Cow::Borrowed($target), false),
            context: CastContext::$context,
            implementation: CastImplementation::Function(CastFunction {
                name: CatalogName::in_pg_catalog(Cow::Borrowed($function), false),
                arguments: Cow::Borrowed(&[$(CatalogName::in_pg_catalog(Cow::Borrowed($argument), false)),+]),
            }),
        }
    };
}

