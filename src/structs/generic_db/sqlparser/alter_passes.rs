//! PostgreSQL alteration preparation and catalog passes.

use alloc::{collections::VecDeque, string::ToString, vec::Vec};

use sqlparser::ast::{
    AlterColumnOperation, AlterTable, AlterTableOperation, AlterTableType, ColumnDef, ColumnOption,
    ColumnOptionDef, Ident, ObjectName, TableConstraint,
};

use super::{
    AlterTableScope, NamedColumn, ParserDB, ParserDBBuilder, StoredTable, TypeArrays,
    constraint_validity, inheritance, referenced_keys, views,
};
use crate::errors::{Error, LookupError};

/// PostgreSQL catalog execution order.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(super) enum Pass {
    Drop,
    AlterType,
    AddColumn,
    TransformConstraint,
    ColumnAttributes,
    IndexConstraint,
    Index,
    OtherConstraint,
    Miscellaneous,
}

impl Pass {
    const ALL: [Self; Self::COUNT] = [
        Self::Drop,
        Self::AlterType,
        Self::AddColumn,
        Self::TransformConstraint,
        Self::ColumnAttributes,
        Self::IndexConstraint,
        Self::Index,
        Self::OtherConstraint,
        Self::Miscellaneous,
    ];
    const COUNT: usize = Self::Miscellaneous as usize + 1;
}

/// Original positions of options already installed on an added column.
pub(super) struct ColumnPositions {
    column: Ident,
    stored: StoredTable,
    present: Vec<usize>,
    default: Option<usize>,
}

/// Constraints whose execution follows column creation.
pub(super) struct DeferredColumn {
    positions: ColumnPositions,
    constraints: Vec<(usize, ColumnOptionDef)>,
}

impl DeferredColumn {
    /// Removes constraints while retaining the column's immediate requirements.
    pub(super) fn extract(column: &mut ColumnDef, stored: &StoredTable) -> Option<Self> {
        if !column.options.iter().any(|option| is_deferred_option(&option.option)) {
            return None;
        }
        if column.options.iter().any(|option| matches!(option.option, ColumnOption::PrimaryKey(_)))
        {
            super::state_not_null(column);
        }
        let default = column
            .options
            .iter()
            .position(|option| matches!(option.option, ColumnOption::Default(_)));
        let position = core::cell::Cell::new(0);
        let mut present = Vec::new();
        let constraints = column
            .options
            .extract_if(.., |option| {
                let original = position.get();
                position.set(original + 1);
                let deferred = is_deferred_option(&option.option);
                if !deferred {
                    present.push(original);
                }
                deferred
            })
            .map(|option| (position.get() - 1, option))
            .collect();
        Some(Self {
            positions: ColumnPositions {
                column: column.name.clone(),
                stored: stored.clone(),
                present,
                default,
            },
            constraints,
        })
    }
}

/// Whether an inline constraint has a catalog pass after column creation.
fn is_deferred_option(option: &ColumnOption) -> bool {
    matches!(
        option,
        ColumnOption::PrimaryKey(_)
            | ColumnOption::Unique(_)
            | ColumnOption::ForeignKey(_)
            | ColumnOption::Check(_)
    )
}

/// Catalog work owned by one alteration statement.
#[expect(
    clippy::large_enum_variant,
    reason = "Inline constraints stay in the pass queues without per-constraint allocations."
)]
pub(super) enum Work {
    Operation(AlterTableOperation),
    ColumnConstraint { column: usize, position: usize, option: ColumnOptionDef },
}

/// Stable queues for catalog passes and their generated work.
pub(super) struct Queue {
    passes: [VecDeque<Work>; Pass::COUNT],
    current: usize,
    columns: Vec<ColumnPositions>,
}

impl Queue {
    /// Schedules commands without changing their order within each pass.
    pub(super) fn new(operations: Vec<AlterTableOperation>, postgres: bool) -> Self {
        let mut queue = Self {
            passes: core::array::from_fn(|_| VecDeque::new()),
            current: 0,
            columns: Vec::new(),
        };
        for operation in operations {
            let pass = if postgres { operation_pass(&operation) } else { Pass::Miscellaneous };
            queue.push(pass, Work::Operation(operation));
        }
        queue
    }

    /// Appends work generated by an earlier catalog pass.
    pub(super) fn push(&mut self, pass: Pass, work: Work) {
        debug_assert!(pass as usize >= self.current);
        self.passes[pass as usize].push_back(work);
    }

    /// Takes the next catalog action in pass order.
    pub(super) fn next(&mut self) -> Option<(Pass, Work)> {
        while self.current < self.passes.len() {
            if let Some(work) = self.passes[self.current].pop_front() {
                return Some((Pass::ALL[self.current], work));
            }
            self.current += 1;
        }
        None
    }

    /// Schedules constraints returned by column creation.
    pub(super) fn defer_column_constraints(&mut self, deferred: DeferredColumn) {
        for (position, option) in deferred.constraints {
            self.push(
                column_constraint_pass(&option.option),
                Work::ColumnConstraint { column: self.columns.len(), position, option },
            );
        }
        self.columns.push(deferred.positions);
    }

    /// Restores an option among the original options already present.
    pub(super) fn option_position(
        &mut self,
        column: usize,
        original: usize,
    ) -> (&ColumnPositions, usize) {
        let positions = &mut self.columns[column];
        let position = positions.present.partition_point(|present| *present < original);
        positions.present.insert(position, original);
        (positions, position)
    }

    /// Removes the original default's position when a command replaces it.
    pub(super) fn replace_default(&mut self, column: &Ident, case: super::IdentifierCase) {
        let named = NamedColumn::of(column, case);
        for positions in &mut self.columns {
            if NamedColumn::of(&positions.column, case).name == named.name
                && let Some(default) = positions.default.take()
            {
                positions.present.retain(|position| *position != default);
            }
        }
    }
}

/// Selects the first catalog pass for a written command.
fn operation_pass(operation: &AlterTableOperation) -> Pass {
    match operation {
        AlterTableOperation::DropColumn { .. }
        | AlterTableOperation::DropConstraint { .. }
        | AlterTableOperation::AlterColumn {
            op:
                AlterColumnOperation::DropDefault
                | AlterColumnOperation::DropNotNull
                | AlterColumnOperation::DropExpression { .. },
            ..
        } => Pass::Drop,
        AlterTableOperation::AlterColumn {
            op: AlterColumnOperation::SetDataType { .. }, ..
        } => Pass::AlterType,
        AlterTableOperation::AddColumn { .. } => Pass::AddColumn,
        AlterTableOperation::AddConstraint { .. } => Pass::TransformConstraint,
        AlterTableOperation::AlterColumn { op: AlterColumnOperation::SetNotNull, .. } => {
            Pass::ColumnAttributes
        }
        AlterTableOperation::AlterColumn {
            op: AlterColumnOperation::SetDefault { .. } | AlterColumnOperation::AddGenerated { .. },
            ..
        } => Pass::OtherConstraint,
        _ => Pass::Miscellaneous,
    }
}

/// Selects the execution pass of a transformed constraint.
pub(super) fn constraint_pass(constraint: &TableConstraint) -> Pass {
    match constraint {
        TableConstraint::PrimaryKeyUsingIndex(_) | TableConstraint::UniqueUsingIndex(_) => {
            Pass::IndexConstraint
        }
        TableConstraint::PrimaryKey(_)
        | TableConstraint::Unique(_)
        | TableConstraint::Exclude(_) => Pass::Index,
        TableConstraint::NotNull(_) => Pass::ColumnAttributes,
        _ => Pass::OtherConstraint,
    }
}

/// Selects the execution pass of an inline constraint.
fn column_constraint_pass(option: &ColumnOption) -> Pass {
    match option {
        ColumnOption::PrimaryKey(_) | ColumnOption::Unique(_) => Pass::Index,
        _ => Pass::OtherConstraint,
    }
}

/// Checks syntax-level constraint restrictions.
pub(super) fn grammar(
    builder: &ParserDBBuilder,
    table_name: &ObjectName,
    operations: &[AlterTableOperation],
) -> Result<(), Error> {
    let constraint_name =
        builder.resolve_table_object_name(table_name)?.map_or(table_name, |table| &table.name);
    for operation in operations {
        match operation {
            AlterTableOperation::AddConstraint { constraint, not_valid } => {
                if let TableConstraint::ForeignKey(key) = constraint {
                    ParserDB::validate_foreign_key_deferral(builder, constraint_name, key)?;
                }
                if *not_valid {
                    constraint_validity::refuse_not_valid(
                        *builder.dialect(),
                        table_name,
                        constraint,
                    )?;
                }
            }
            AlterTableOperation::AddColumn { column_def, .. } => {
                for option in &column_def.options {
                    if let ColumnOption::ForeignKey(key) = &option.option {
                        ParserDB::validate_foreign_key_deferral(builder, constraint_name, key)?;
                    }
                }
            }
            _ => {}
        }
    }
    Ok(())
}

/// Validates a table constraint before its execution pass.
pub(super) fn transform_constraint(
    builder: &ParserDBBuilder,
    table_name: &ObjectName,
    scope: AlterTableScope,
    constraint: &TableConstraint,
) -> Result<Pass, Error> {
    if let Some(stored) = ParserDB::alter_table_target(builder, table_name, scope)? {
        if let TableConstraint::PrimaryKeyUsingIndex(adoption)
        | TableConstraint::UniqueUsingIndex(adoption) = constraint
        {
            super::constraint_using_index::validate_adoption(
                builder,
                &stored,
                &adoption.index_name,
            )?;
        }
        ParserDB::refuse_repeated_added_key_column(builder, &stored, constraint)?;
    }
    Ok(constraint_pass(constraint))
}

/// Commands accepted only as the sole action in their statement.
#[derive(Clone, Copy, PartialEq, Eq)]
pub(super) enum Standalone {
    Rename,
    Partition,
    SetSchema,
}

/// Classifies commands whose syntax has no comma-separated form.
pub(super) fn standalone(operation: &AlterTableOperation) -> Option<Standalone> {
    match operation {
        AlterTableOperation::RenameTable { .. }
        | AlterTableOperation::RenameColumn { .. }
        | AlterTableOperation::RenameConstraint { .. } => Some(Standalone::Rename),
        AlterTableOperation::AttachPartitionOf { .. }
        | AlterTableOperation::DetachPartitionOf { .. } => Some(Standalone::Partition),
        AlterTableOperation::SetSchema { .. } => Some(Standalone::SetSchema),
        _ => None,
    }
}

/// Refuses combined standalone commands at their first invalid token.
pub(super) fn require_standalone(
    builder: &ParserDBBuilder,
    statement: &AlterTable,
) -> Result<(), Error> {
    if statement.operations.len() < 2 {
        return Ok(());
    }
    let postgres = matches!(builder.dialect(), super::SqlparserDialect::PostgreSql);
    let Some((position, kind)) =
        statement.operations.iter().enumerate().find_map(|(position, operation)| {
            let kind = standalone(operation)?;
            (postgres || kind == Standalone::Partition).then_some((position, kind))
        })
    else {
        return Ok(());
    };
    let operation = &statement.operations[position];
    let keyword = match operation {
        AlterTableOperation::SetSchema { .. } => "SCHEMA",
        AlterTableOperation::AttachPartitionOf { .. } => "ATTACH",
        AlterTableOperation::DetachPartitionOf { .. } => "DETACH",
        AlterTableOperation::RenameConstraint { .. }
            if position == 0 && statement.table_type == Some(AlterTableType::Foreign) =>
        {
            "CONSTRAINT"
        }
        _ => "RENAME",
    };
    let foreign_refusal = statement.table_type == Some(AlterTableType::Foreign)
        && matches!(
            operation,
            AlterTableOperation::RenameConstraint { .. }
                | AlterTableOperation::AttachPartitionOf { .. }
                | AlterTableOperation::DetachPartitionOf { .. }
        );
    let written_token = if position == 0 && !foreign_refusal { "," } else { keyword }.to_string();
    Err(match kind {
        Standalone::Rename => {
            Error::RenameCommandNotAlone {
                relation_name: builder.dialect().stored_object_name(&statement.name),
                written_token,
            }
        }
        Standalone::Partition => {
            Error::PartitionCommandNotAlone {
                table_name: builder.dialect().stored_object_name_last(&statement.name),
                written_token,
            }
        }
        Standalone::SetSchema => Error::SetSchemaCommandNotAlone { written_token },
    })
}

/// Whether a relation kind refuses an alteration operation.
pub(super) fn refuses(kind: super::ObjectKind, operation: &AlterTableOperation) -> bool {
    match kind {
        super::ObjectKind::VirtualTable => {
            !matches!(operation, AlterTableOperation::RenameTable { .. })
        }
        super::ObjectKind::ForeignTable => super::foreign_table_refuses(operation),
        _ => super::needs_foreign_table(operation),
    }
}

/// Checks one command against the catalog at its preparation boundary.
pub(super) fn prepare(
    builder: &ParserDBBuilder,
    table_name: &ObjectName,
    scope: AlterTableScope,
    operation: &mut AlterTableOperation,
    arrays: &TypeArrays,
    persistence: &mut Option<bool>,
) -> Result<(), Error> {
    let postgres = matches!(builder.dialect(), super::SqlparserDialect::PostgreSql);
    if !postgres {
        if let AlterTableOperation::AlterColumn {
            op: AlterColumnOperation::SetDataType { data_type, .. },
            ..
        } = operation
        {
            super::domains::bind_type(builder, data_type, arrays)?;
        }
        if builder.resolve_table_object_name(table_name)?.is_none() {
            return Ok(());
        }
    }
    let Some(stored) = ParserDB::alter_table_target(builder, table_name, scope)? else {
        return Ok(());
    };
    let node = ParserDB::stored_node(builder, &stored)?;
    let object_kind = builder.stored_table_kind(node);
    if refuses(object_kind, operation) {
        return Err(Error::AlterActionUnsupportedOnRelation {
            object_kind,
            relation_name: builder.dialect().stored_object_name_last(table_name),
            operation: operation.to_string(),
            action: views::alter_action(operation, object_kind),
        });
    }
    match operation {
        AlterTableOperation::AlterColumn {
            column_name,
            op:
                operation @ (AlterColumnOperation::SetDataType { .. }
                | AlterColumnOperation::DropExpression { .. }),
        } => {
            super::stored_expressions::refuse_in_column_change(builder, operation)?;
            if postgres && matches!(operation, AlterColumnOperation::DropExpression { .. }) {
                ParserDB::refuse_only_with_children(
                    builder,
                    &stored,
                    scope,
                    crate::errors::InheritedChange::DropExpression,
                    Some(column_name),
                )?;
            }
            let column = NamedColumn::of(column_name, builder.identifier_case());
            let dialect = builder.dialect();
            if !column.declared_by(node) {
                return Err(LookupError::ColumnNotFound {
                    table_name: dialect.stored_spelling(&stored.name, stored.name_quoted),
                    column_name: dialect.stored_spelling(&column.name, column.quoted),
                    site: crate::errors::ColumnLookupSite::Relation,
                }
                .into());
            }
            match operation {
                AlterColumnOperation::SetDataType { data_type, .. } => {
                    if inheritance::is_inherited_column(builder, node, column_name) {
                        return Err(Error::InheritedColumnTypeNotAlterable {
                            table_name: dialect.stored_spelling(&stored.name, stored.name_quoted),
                            column_name: dialect.stored_spelling(&column.name, column.quoted),
                        });
                    }
                    if postgres {
                        super::domains::bind_type(builder, data_type, arrays)?;
                    }
                    ParserDB::refuse_only_with_children(
                        builder,
                        &stored,
                        scope,
                        crate::errors::InheritedChange::AlterColumnType,
                        Some(column_name),
                    )?;
                }
                AlterColumnOperation::DropExpression { .. } if postgres => {
                    ParserDB::refuse_inherited_expression_drop(
                        builder,
                        &stored,
                        node,
                        &column,
                        column_name,
                    )?;
                }
                _ => {}
            }
        }
        AlterTableOperation::Inherit { .. } => {
            super::alter_inheritance::refuse_inheritance_child(builder, node)?;
        }
        AlterTableOperation::SetLogged | AlterTableOperation::SetUnlogged => {
            ParserDB::prepare_table_persistence(
                builder,
                &stored,
                matches!(operation, AlterTableOperation::SetUnlogged),
                persistence,
            )?;
        }
        _ => {}
    }
    Ok(())
}

/// Installs an inline constraint after column creation.
pub(super) fn install_column_constraint(
    mut builder: ParserDBBuilder,
    table_name: &ObjectName,
    scope: AlterTableScope,
    column: &ColumnPositions,
    position: usize,
    mut option: ColumnOptionDef,
    persistence: Option<bool>,
) -> Result<ParserDBBuilder, Error> {
    let stored = &column.stored;
    ParserDB::refuse_unaddable_column_option(&builder, stored, &option)?;
    ParserDB::refuse_column_reference_from_permanent_start(
        &builder,
        table_name,
        persistence,
        &option,
    )?;
    let Ok(bound_to_primary) = referenced_keys::bind_noting_primary_key(
        &mut option,
        referenced_keys::option_foreign_keys,
        |option| {
            if let ColumnOption::ForeignKey(key) = &mut option.option {
                builder.bind_foreign_key_at_declaration(key);
            }
            Ok::<(), core::convert::Infallible>(())
        },
    );
    builder = ParserDB::alter_table_column_def(
        builder,
        table_name,
        scope,
        &column.column,
        &option.option,
        false,
        |declared| {
            declared.options.insert(position.min(declared.options.len()), option.clone());
        },
    )?;
    referenced_keys::record_primary_key_references(&mut builder, stored, &bound_to_primary);
    Ok(builder)
}
