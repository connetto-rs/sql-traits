//! Tests that a `serial` or identity column brings the sequence PostgreSQL
//! creates for it, under the name, in the schema and with the type
//! PostgreSQL gives it, owned by the column and gone with it.
//!
//! Every expectation was measured against PostgreSQL 18.4.
#![allow(clippy::expect_used, clippy::panic)]

use sql_traits::{
    errors::{Error, ObjectKind},
    prelude::*,
};
use sqlparser::dialect::{GenericDialect, PostgreSqlDialect};

fn parse(sql: &str) -> Result<ParserDB, Error> {
    ParserDB::parse::<PostgreSqlDialect>(sql)
}

/// Every sequence as `schema.name origin options owner`, sorted.
fn described(database: &ParserDB) -> Vec<String> {
    let mut sequences: Vec<String> = database
        .sequences()
        .map(|sequence| {
            let options: String =
                sequence.options().iter().map(ToString::to_string).collect::<String>();
            let owner = match sequence.owner(database) {
                Some(SequenceOwner::Column(column)) => {
                    format!(
                        "{}.{}",
                        ColumnLike::table(column, database).table_name(),
                        column.column_name()
                    )
                }
                Some(SequenceOwner::ViewColumn { view, ordinal }) => {
                    format!("{}#{ordinal}", view.view_name())
                }
                None => "none".to_string(),
            };
            format!(
                "{}.{} {:?}{options} owned by {owner}",
                sequence.sequence_schema().unwrap_or("public"),
                sequence.sequence_name(),
                sequence.origin(),
            )
        })
        .collect();
    sequences.sort();
    sequences
}

include!(concat!(env!("CARGO_MANIFEST_DIR"), "/tests/support/sequence_names.rs"));

const NONE: [&str; 0] = [];

#[test]
fn each_serial_kind_brings_a_sequence_of_its_width() {
    let db = parse(
        "CREATE TABLE t (a serial, b bigserial, c smallserial, d serial4, e serial8, f serial2);",
    )
    .expect("schema parses");
    assert_eq!(
        described(&db),
        [
            "public.t_a_seq Serial AS INTEGER owned by t.a",
            "public.t_b_seq Serial AS BIGINT owned by t.b",
            "public.t_c_seq Serial AS SMALLINT owned by t.c",
            "public.t_d_seq Serial AS INTEGER owned by t.d",
            "public.t_e_seq Serial AS BIGINT owned by t.e",
            "public.t_f_seq Serial AS SMALLINT owned by t.f",
        ]
    );
}

#[test]
fn an_identity_column_brings_a_sequence_with_its_options() {
    let db = parse(
        "CREATE TABLE t (
             a INT GENERATED ALWAYS AS IDENTITY,
             b BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 5 INCREMENT BY 2)
         );",
    )
    .expect("schema parses");
    assert_eq!(
        described(&db),
        [
            "public.t_a_seq Identity AS INT owned by t.a",
            "public.t_b_seq Identity AS BIGINT START WITH 5 INCREMENT BY 2 owned by t.b",
        ]
    );
}

#[test]
fn a_declared_sequence_says_so() {
    let db = parse("CREATE SEQUENCE s;").expect("schema parses");
    assert_eq!(described(&db), ["public.s Declared owned by none"]);
}

#[test]
fn a_long_name_is_cut_the_way_postgresql_cuts_it() {
    let table = "a".repeat(40);
    let column = "b".repeat(40);
    let db = parse(&format!("CREATE TABLE {table} ({column} serial);")).expect("schema parses");
    assert_eq!(sequence_names(&db), [format!("public.{}_{}_seq", "a".repeat(29), "b".repeat(29))]);

    // The column name itself is cut to 63 bytes first.
    let db = parse(&format!("CREATE TABLE t ({} serial);", "c".repeat(70))).expect("parses");
    assert_eq!(sequence_names(&db), [format!("public.t_{}_seq", "c".repeat(57))]);

    // A cut never splits a character.
    let db = parse(&format!("CREATE TABLE t ({} serial);", "é".repeat(40))).expect("parses");
    assert_eq!(sequence_names(&db), [format!("public.t_{}_seq", "é".repeat(28))]);
}

#[test]
fn a_taken_name_gets_the_next_free_number() {
    let db = parse("CREATE SEQUENCE t_id_seq; CREATE TABLE t (id serial);").expect("parses");
    assert_eq!(sequence_names(&db), ["public.t_id_seq", "public.t_id_seq1"]);

    let db = parse("CREATE TABLE t_id_seq (x INT); CREATE TABLE t (id serial);").expect("parses");
    assert_eq!(sequence_names(&db), ["public.t_id_seq1"]);

    let db = parse(
        "CREATE SEQUENCE t_id_seq;
         CREATE SEQUENCE t_id_seq1;
         CREATE TABLE t (id serial);",
    )
    .expect("parses");
    assert_eq!(sequence_names(&db), ["public.t_id_seq", "public.t_id_seq1", "public.t_id_seq2"]);

    // Two columns of one statement do not see each other's name.
    let a = format!("{}x", "c".repeat(60));
    let b = format!("{}y", "c".repeat(60));
    assert!(matches!(
        parse(&format!("CREATE TABLE t ({a} serial, {b} serial);")),
        Err(Error::RelationNameAlreadyTaken {
            object_kind: ObjectKind::Sequence,
            conflicting_kind: ObjectKind::Sequence,
            ..
        })
    ));
}

#[test]
fn the_name_keeps_the_stored_spelling_of_its_parts() {
    let db = parse("CREATE TABLE \"T\" (\"Id\" serial, Other serial);").expect("parses");
    assert_eq!(sequence_names(&db), ["public.T_Id_seq", "public.T_other_seq"]);
    let sequence = db
        .sequence_by_target(TargetName::new("T_Id_seq", true), IdentifierCase::AsWritten)
        .expect("the name is well formed")
        .expect("the case is kept");
    assert!(sequence.sequence_name_is_quoted());
}

#[test]
fn the_sequence_lands_in_the_schema_of_its_table() {
    let db = parse(
        "CREATE SCHEMA app;
         CREATE TABLE app.a (id serial);
         SET search_path = app;
         CREATE TABLE b (id serial);
         CREATE TEMP TABLE c (id serial);",
    )
    .expect("parses");
    assert_eq!(sequence_names(&db), ["app.a_id_seq", "app.b_id_seq", "pg_temp.c_id_seq"]);
}

#[test]
fn adding_a_column_or_an_identity_brings_a_sequence() {
    let db = parse(
        "CREATE TABLE t (x INT, y INT NOT NULL);
         ALTER TABLE t ADD COLUMN a serial;
         ALTER TABLE t ADD COLUMN b BIGINT GENERATED ALWAYS AS IDENTITY;
         ALTER TABLE t ALTER COLUMN y ADD GENERATED ALWAYS AS IDENTITY;
         ALTER TABLE t ADD COLUMN IF NOT EXISTS a serial;",
    )
    .expect("parses");
    assert_eq!(
        described(&db),
        [
            "public.t_a_seq Serial AS INTEGER owned by t.a",
            "public.t_b_seq Identity AS BIGINT owned by t.b",
            "public.t_y_seq Identity AS INT owned by t.y",
        ]
    );
}

#[test]
fn copied_columns_bring_no_sequence() {
    let db = parse(
        "CREATE TABLE t (id serial, j INT GENERATED ALWAYS AS IDENTITY, k INT) PARTITION BY RANGE (k);
         CREATE TABLE p1 PARTITION OF t FOR VALUES FROM (0) TO (10);
         CREATE TABLE plain (id serial);
         CREATE TABLE child () INHERITS (plain);
         CREATE TABLE copy (LIKE plain);
         CREATE TABLE IF NOT EXISTS t (other serial);",
    )
    .expect("parses");
    assert_eq!(sequence_names(&db), ["public.plain_id_seq", "public.t_id_seq", "public.t_j_seq"]);
}

#[test]
fn the_sequence_keeps_its_name_and_leaves_with_its_column() {
    let db = parse(
        "CREATE TABLE t (id serial, k INT GENERATED ALWAYS AS IDENTITY, x INT);
         ALTER TABLE t RENAME TO u;
         ALTER TABLE u RENAME COLUMN id TO renamed;",
    )
    .expect("parses");
    assert_eq!(
        described(&db),
        [
            "public.t_id_seq Serial AS INTEGER owned by u.renamed",
            "public.t_k_seq Identity AS INT owned by u.k",
        ]
    );

    let db = parse(
        "CREATE TABLE t (id serial, k INT GENERATED ALWAYS AS IDENTITY);
         ALTER TABLE t DROP COLUMN id;",
    )
    .expect("parses");
    assert_eq!(sequence_names(&db), ["public.t_k_seq"]);

    let db = parse(
        "CREATE SCHEMA app;
         CREATE TABLE app.t (id serial);
         CREATE TABLE u (id BIGINT GENERATED ALWAYS AS IDENTITY);
         DROP TABLE u;
         DROP SCHEMA app CASCADE;",
    )
    .expect("parses");
    assert_eq!(sequence_names(&db), NONE);
}

#[test]
fn an_identity_sequence_follows_its_column_type() {
    let db = parse(
        "CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY (START WITH 3), s serial);
         ALTER TABLE t ALTER COLUMN id TYPE BIGINT;
         ALTER TABLE t ALTER COLUMN s TYPE BIGINT;",
    )
    .expect("parses");
    assert_eq!(
        described(&db),
        [
            "public.t_id_seq Identity AS BIGINT START WITH 3 owned by t.id",
            "public.t_s_seq Serial AS INTEGER owned by t.s",
        ]
    );
}

#[test]
fn an_identity_sequence_cannot_be_dropped_on_its_own() {
    for drop in ["DROP SEQUENCE t_id_seq;", "DROP SEQUENCE t_id_seq CASCADE;"] {
        assert!(
            matches!(
                parse(&format!("CREATE TABLE t (id INT GENERATED ALWAYS AS IDENTITY); {drop}")),
                Err(Error::SequenceRequiredByColumn { ref sequence_name, ref table_name, ref column_name })
                    if sequence_name == "t_id_seq" && table_name == "t" && column_name == "id"
            ),
            "{drop}"
        );
    }
}

#[test]
fn only_postgresql_creates_sequences_for_columns() {
    let db = ParserDB::parse::<GenericDialect>(
        "CREATE TABLE t (id serial, k INT GENERATED ALWAYS AS IDENTITY);",
    )
    .expect("parses");
    assert_eq!(sequence_names(&db), NONE);
}
