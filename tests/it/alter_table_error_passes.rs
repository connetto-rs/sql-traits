#[test]
fn measured_pass_pairs() {
    let mut failures = Vec::new();
    for &(first, second, expected) in MEASURED_PAIRS {
        let sql = format!("CREATE TABLE probe(z int); ALTER TABLE probe {first}, {second};");
        let result = ParserDB::parse::<PostgreSqlDialect>(&sql);
        if !matches!(&result, Err(error) if format!("{error:?}") == expected) {
            failures.push(format!("{sql} expected {expected}, received {result:?}"));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

