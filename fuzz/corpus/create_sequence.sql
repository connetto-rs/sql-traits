CREATE SCHEMA app;
CREATE TABLE app.tickets (id BIGINT, label TEXT);
CREATE VIEW app.labels AS SELECT id, label FROM app.tickets;
SET search_path = app, public;
CREATE SEQUENCE ticket_seq AS BIGINT INCREMENT BY 1 MINVALUE 1 NO MAXVALUE START WITH 100 CACHE 10 NO CYCLE OWNED BY tickets.id;
CREATE SEQUENCE label_seq OWNED BY labels.label;
CREATE TEMP SEQUENCE IF NOT EXISTS scratch;
GRANT USAGE ON SEQUENCE ticket_seq TO PUBLIC;
ALTER TABLE tickets RENAME COLUMN id TO ticket_id;
DROP SEQUENCE scratch;
DROP TABLE tickets CASCADE;
DROP SCHEMA app CASCADE;
